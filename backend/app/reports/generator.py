from typing import Dict, Any, List
from datetime import datetime, timezone


class ReportGenerator:
    @staticmethod
    def generate_markdown(
        session: Any,
        sources: List[Any],
        requirements: List[Any],
        conflicts: List[Any],
        blindspots: List[Any]
    ) -> str:
        date_str = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
        lines = [
            f"# PROOFPATH AI — FORENSIC INVESTIGATION REPORT",
            f"> *\"Know what's missing before you decide.\"*",
            f"",
            f"**Project Title**: {session.title}  ",
            f"**Research Goal**: {session.research_goal}  ",
            f"**Target Decision**: {session.target_decision or 'N/A'}  ",
            f"**Generated At**: {date_str}  ",
            f"**Investigation Status**: {session.status.upper()}  ",
            f"",
            f"---",
            f"",
            f"## 1. Executive Verdict & Decision-Readiness Index (DRI)",
            f"",
            f"### **Overall Score: {session.readiness_score} / 100**",
            f"**Verdict**: {session.executive_verdict or 'Audit pending'}",
            f"",
            f"| Metric Dimension | Score | Weight | Assessment |",
            f"|---|---|---|---|",
            f"| **Coverage** | {session.coverage_score}% | 35% | Evaluates if all criteria have evidence |",
            f"| **Consistency** | {session.consistency_score}% | 30% | Penalizes cross-source contradictions |",
            f"| **Freshness** | {session.freshness_score}% | 15% | Audits publication dates & temporal decay |",
            f"| **Verification** | {session.verification_score}% | 20% | Measures verbatim quote fidelity |",
            f"",
            f"---",
            f"",
            f"## 2. Ingested Evidence Sources ({len(sources)})",
            f"",
        ]

        for idx, s in enumerate(sources, 1):
            pub = s.publication_date.strftime("%Y-%m-%d") if s.publication_date else "Unknown"
            lines.append(f"{idx}. **{s.title}** (`{s.source_type.upper()}`)")
            lines.append(f"   - URI/Location: {s.uri or 'Uploaded Document'}")
            lines.append(f"   - Publication Date: {pub}")
            lines.append("")

        lines.extend([
            f"---",
            f"",
            f"## 3. Evaluation Criteria & Evidence Coverage ({len(requirements)})",
            f"",
            f"| # | Requirement | Category | Status | Weight |",
            f"|---|---|---|---|---|",
        ])

        for idx, r in enumerate(requirements, 1):
            status_badge = r.status.upper()
            lines.append(f"| {idx} | {r.requirement_text} | `{r.category}` | **{status_badge}** | {r.weight} |")

        lines.extend([
            f"",
            f"---",
            f"",
            f"## 4. Cross-Source Contradictions & Conflicts ({len(conflicts)})",
            f"",
        ])

        if not conflicts:
            lines.append("*(No cross-source contradictions were detected across provided documents.)*")
            lines.append("")
        else:
            for c_idx, c in enumerate(conflicts, 1):
                claim_a = getattr(c, "claim_a", None)
                claim_b = getattr(c, "claim_b", None)
                source_a = claim_a.chunk.source.title if claim_a and claim_a.chunk and claim_a.chunk.source else "Source A"
                source_b = claim_b.chunk.source.title if claim_b and claim_b.chunk and claim_b.chunk.source else "Source B"
                quote_a = claim_a.exact_quote if claim_a else ""
                quote_b = claim_b.exact_quote if claim_b else ""

                lines.append(f"### Conflict #{c_idx}: [{c.severity.upper()} SEVERITY] {c.conflicting_aspect}")
                lines.append(f"- **Source A ({source_a}) Quote**: \"{quote_a}\"")
                lines.append(f"- **Source B ({source_b}) Quote**: \"{quote_b}\"")
                lines.append(f"- **Forensic Synthesis**: {c.synthesis_verdict}")
                lines.append("")

        lines.extend([
            f"---",
            f"",
            f"## 5. BlindSpots — Critical Questions You Forgot to Ask ({len(blindspots)})",
            f"",
        ])

        for b_idx, b in enumerate(blindspots, 1):
            lines.append(f"### {b_idx}. {b.question}")
            lines.append(f"- **Risk Level**: `{b.risk_level.upper()}` | **Category**: `{b.category}`")
            lines.append(f"- **Operational Rationale**: {b.rationale}")
            lines.append(f"- [ ] Human Verification Sign-off")
            lines.append("")

        lines.extend([
            f"---",
            f"*Report generated by PROOFPATH AI Engine. Verbatim quotes substring-verified.*"
        ])

        return "\n".join(lines)
